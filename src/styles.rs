//! Artist styles: each one is a whole vocal chain, written as parameter id -> plain value on top
//! of the defaults. They're our reading of the characteristic sound on these artists'
//! records, as starting points; nothing here comes from, or is endorsed by, the artists.
//!
//! Enum values are indices:
//!   scale    0 Chromatic 1 Major 2 Minor ...      voice   0 Low 1 Mid 2 High 3 Wide
//!   sat_mode 0 Tape 1 Tube 2 Fuzz 3 Phone 4 LoFi  dly_div 0 1/16 1 1/8T 2 1/8 3 1/8D 4 1/4T
//!   rev_type 0 Plate 1 Room 2 Hall 3 Chamber              5 1/4 6 1/4D 7 1/2 8 1/2D 9 bar

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Tag {
    Lyrical,
    Melodic,
    HardTune,
    Gritty,
    Smooth,
    Rage,
    OldSchool,
    Spacey,
    Female,
}

impl Tag {
    pub const ALL: [Tag; 9] = [
        Tag::Lyrical,
        Tag::Melodic,
        Tag::HardTune,
        Tag::Gritty,
        Tag::Smooth,
        Tag::Rage,
        Tag::OldSchool,
        Tag::Spacey,
        Tag::Female,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Tag::Lyrical => "Lyrical",
            Tag::Melodic => "Melodic",
            Tag::HardTune => "Hard tune",
            Tag::Gritty => "Gritty",
            Tag::Smooth => "Smooth",
            Tag::Rage => "Rage",
            Tag::OldSchool => "Old school",
            Tag::Spacey => "Spacey",
            Tag::Female => "Women in rap",
        }
    }
}

pub struct Style {
    pub name: &'static str,
    pub tags: &'static [Tag],
    /// One line on the sound, shown on the card.
    pub blurb: &'static str,
    /// Card gradient, 0xRRGGBB.
    pub colors: [u32; 2],
    /// How hard the compressors work on a vocal at the design level (-18 dBFS RMS), in dB of
    /// gain reduction: Punch on the loudest words (95th percentile), Level on average. The
    /// `calibrate_styles` test sets the thresholds and the trim from these.
    pub squeeze: (f32, f32),
    pub values: &'static [(&'static str, f32)],
}

/// Parameters that belong to the singer or the song, not the sound: loading a style keeps them.
pub const KEEP_ON_STYLE: &[&str] = &[
    "in", "out", "mix", "lim_on", "lim_ceil", "t_key", "t_scale", "t_voice", "m_amt", "m_b0", "m_b1", "m_b2", "m_b3", "m_b4",
    "m_b5", "m_b6", "m_b7",
];

macro_rules! v {
    ($($id:literal = $val:expr),* $(,)?) => { &[$(($id, $val as f32)),*] };
}

